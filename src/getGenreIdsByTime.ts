  // 昼下がり 14時：休憩・育児の合間（スイーツ・キッズ・バッグ）
  14: ["551167", "100533", "216131"],

  // ゴールデンタイム 20時：リラックス・買い物意欲増（インテリア・キッチン・美容）
  20: ["100804", "558944", "100939"],

  // 深夜 23時：寝る前のチェック（スマホ・家電・本・下着）
  23: ["100433", "565950", "200162"],
